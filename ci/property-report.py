#!/usr/bin/env python3
"""Merge the Hypothesis, fast-check and mutation results into one file (published as https://kolaboro.com/data/property-tests.json).
Usage: python3 ci/property-report.py py.json js.json mutation.json out.json"""
import hashlib, json, os, subprocess, sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
py, js, mu = (json.load(open(p)) for p in sys.argv[1:4])
sha = lambda p: hashlib.sha256(open(os.path.join(ROOT, p), 'rb').read()).hexdigest()
try:
    commit = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=ROOT, capture_output=True, text=True).stdout.strip() or None
except OSError:
    commit = None
props = [dict(p, suite='python') for p in py['properties']] + [dict(p, suite='javascript') for p in js['properties']]
out = {
    'about': 'Property-based tests and fuzzing of Kolaboro\'s open scoring rules. Generated by the open-source repository CI; every number below is counted by the test run itself.',
    'generated': datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
    'commit': commit or os.environ.get('GITHUB_SHA'),
    'run_url': (os.environ.get('GITHUB_SERVER_URL', '') + '/' + os.environ.get('GITHUB_REPOSITORY', '') + '/actions/runs/' + os.environ['GITHUB_RUN_ID']) if os.environ.get('GITHUB_RUN_ID') else None,
    'files_tested': {p: sha(p) for p in ['open/scoring.py', 'p/whatif.js', 'transparency-index/ti-core.js']},
    'engines': [py['engine'], js['engine']],
    'seed_javascript': js.get('seed'),
    'cases_total': py['cases'] + js['cases'],
    'properties_total': len(props),
    'properties_passed': sum(1 for p in props if p['passed']),
    'known_issues': [p['id'] for p in props if p.get('known_issue')],
    'passed': py['passed'] and js['passed'],
    'mutation': mu,
    'properties': [{k: p.get(k) for k in ('suite', 'id', 'property', 'cases', 'passed', 'known_issue', 'mismatches', 'counterexample')} for p in props],
}
json.dump(out, open(sys.argv[4], 'w'), indent=1, ensure_ascii=False)
print('%d cases, %d of %d properties pass, known issues: %s, mutants caught %d of %d' % (out['cases_total'], out['properties_passed'], out['properties_total'], out['known_issues'] or 'none', mu['caught'], mu['total']))
